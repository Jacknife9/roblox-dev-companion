import { readFileSync, writeFileSync } from 'node:fs';
import { templates } from '../src/data/templates';
// Embed each template as a Luau long string whose level never collides with its contents.
const long = (s: string) => { let eq = ''; while (s.includes(`]${eq}]`)) eq += '='; return `[${eq}[\n${s}]${eq}]`; };
const str = (s: string) => JSON.stringify(s); // Template metadata is plain text; JSON string escapes are valid Luau.
const list = templates.map(t => `\t{ title = ${str(t.title)}, category = ${str(t.category)}, kind = ${str(t.kind)}, placement = ${str(t.placement)}, code = ${long(t.code)} },`).join('\n');
const source = readFileSync('studio-plugin/DevCompanion.src.lua', 'utf8');
if (!source.includes('--@TEMPLATES')) throw new Error('Template marker missing.');
writeFileSync('studio-plugin/DevCompanion.lua', `-- GENERATED by npm run build:plugin. Edit DevCompanion.src.lua instead.\n${source.replace('--@TEMPLATES', `{\n${list}\n}`)}`);
console.log(`Built studio-plugin/DevCompanion.lua with ${templates.length} templates.`);
